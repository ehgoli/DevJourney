/*
 * تعیین زودهنگام پوسته (روشن/تاریک) — جلوگیری از چشمک‌زدن صفحه
 * -------------------------------------------------------
 * این فایل باید همیشه با یک تگ <script> عادی (بدون async و
 * بدون defer) در همان ابتدای <head>، پیش از تمام لینک‌های CSS
 * لود شود؛ یعنی دقیقاً همین‌جایی که الان هست. اسکریپت‌های
 * خارجیِ غیر-async درست مثل اسکریپت inline، رندر صفحه را تا
 * اجرا شدن‌شان متوقف می‌کنند — پس با وجود اینکه این فایل
 * جداست، هیچ چشمک‌زدنی رخ نمی‌دهد و در عین حال <head> هر صفحه
   یک خط تمیز است، نه چند خط جاوااسکریپت تکرارشده.
 *
 * پوسته‌ی پیش‌فرض (وقتی کاربر هنوز چیزی انتخاب نکرده — اولین
 * بازدید) عمداً به تنظیمات سیستم‌عامل کاربر (prefers-color-
 * scheme) وابسته نیست، چون صاحب سایت می‌خواهد خودش تصمیم
 * بگیرد اولین برداشت بازدیدکننده روشن باشد یا تاریک. برای
 * تغییرش فقط همین یک خط زیر را عوض کن:
 */
var DEFAULT_THEME = "light"; // مقدار مجاز: "light" یا "dark"

(function () {
    try {
        var saved = localStorage.getItem("theme");
        var theme = saved === "dark" || saved === "light" ? saved : DEFAULT_THEME;
        document.documentElement.setAttribute("data-bs-theme", theme);
    } catch (e) {
        document.documentElement.setAttribute("data-bs-theme", DEFAULT_THEME);
    }
})();
